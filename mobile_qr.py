#!/usr/bin/env python3
"""
Generate a QR code for importing ATC config into the Android mobile app.

Secrets are resolved automatically from your macOS Keychain — no copy-pasting tokens.

The payload is ALWAYS passphrase-encrypted before it goes into the QR (terminal
ASCII art and --save PNG both carry ciphertext, never plaintext secrets). You
pick a passphrase interactively each run; it's never written to disk or passed
as an argument. Give the same passphrase to the Android app when it scans the
code. Wire format — see ATCQR1_PREFIX below for the exact byte layout.

Usage (from infrastructure/cli/):
    python mobile_qr.py                          # terminal QR, all services
    python mobile_qr.py --save ~/Desktop/qr.png  # also save as PNG (requires Pillow)
    python mobile_qr.py --only proxmox           # single service
    python mobile_qr.py --only proxmox,portainer # specific subset
    python mobile_qr.py --print-yaml             # show the generated YAML (plaintext,
                                                  # pre-encryption — for local debugging only)

Then in the Android app: Settings → Scan QR Code, enter the same passphrase.

NOTE: this changes the QR wire format from plaintext YAML to encrypted bytes
(see ATCQR1_PREFIX). The Android-side scanner needs a matching decrypt step
(scrypt KDF + AES-256-GCM, exact layout documented below) before it can import
a QR generated by this version.

Install deps (first time only):
    uv sync
    uv add "qrcode[pil]"   # [pil] is optional, needed only for --save PNG
"""
from __future__ import annotations

import argparse
import base64
import getpass
import os
import sys
from pathlib import Path

# Allow running directly from the CLI root directory
sys.path.insert(0, str(Path(__file__).parent))

try:
    import qrcode
    import qrcode.constants
except ImportError:
    print("qrcode not installed.  Run:  uv add qrcode")
    sys.exit(1)

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt

import yaml
from src.config import load_config

# ── Passphrase encryption ─────────────────────────────────────────────────────
#
# Wire format (everything after the ASCII prefix is raw bytes, base64'd for the
# QR/terminal so it stays in printable ASCII):
#
#   "ATCQR1:" + base64( salt(16 bytes) + nonce(12 bytes) + ciphertext_and_tag )
#
# Key derivation: scrypt(passphrase, salt, n=2**15, r=8, p=1, length=32) — a
# fresh random salt every run, so the same passphrase never derives the same
# key twice. Cipher: AES-256-GCM (nonce is also fresh-random per run; GCM's
# standard 16-byte tag is appended to the ciphertext by `AESGCM.encrypt`, not
# transmitted separately). This matches the KDF/cipher pair already used by
# atc's own `keyrings.cryptfile` secrets backend (see `atc secrets
# migrate-encryption`), rather than inventing a second crypto scheme.
ATCQR1_PREFIX = "ATCQR1:"
_SCRYPT_N = 2 ** 15
_SCRYPT_R = 8
_SCRYPT_P = 1
_KEY_LEN = 32
_SALT_LEN = 16
_NONCE_LEN = 12


def _derive_key(passphrase: str, salt: bytes) -> bytes:
    kdf = Scrypt(salt=salt, length=_KEY_LEN, n=_SCRYPT_N, r=_SCRYPT_R, p=_SCRYPT_P)
    return kdf.derive(passphrase.encode("utf-8"))


def encrypt_payload(plaintext: str, passphrase: str) -> str:
    """Return the ATCQR1-prefixed, base64-encoded encrypted payload."""
    salt = os.urandom(_SALT_LEN)
    nonce = os.urandom(_NONCE_LEN)
    key = _derive_key(passphrase, salt)
    ciphertext = AESGCM(key).encrypt(nonce, plaintext.encode("utf-8"), associated_data=None)
    blob = salt + nonce + ciphertext
    return ATCQR1_PREFIX + base64.b64encode(blob).decode("ascii")


def decrypt_payload(encoded: str, passphrase: str) -> str:
    """Inverse of encrypt_payload — used only by this script's own self-test."""
    if not encoded.startswith(ATCQR1_PREFIX):
        raise ValueError("Not an ATCQR1 payload")
    blob = base64.b64decode(encoded[len(ATCQR1_PREFIX):])
    salt, nonce, ciphertext = blob[:_SALT_LEN], blob[_SALT_LEN:_SALT_LEN + _NONCE_LEN], blob[_SALT_LEN + _NONCE_LEN:]
    key = _derive_key(passphrase, salt)
    plaintext = AESGCM(key).decrypt(nonce, ciphertext, associated_data=None)
    return plaintext.decode("utf-8")


def _prompt_passphrase() -> str:
    while True:
        p1 = getpass.getpass("QR passphrase (shared with the Android app at scan time): ")
        if len(p1) < 8:
            print("  Too short — use at least 8 characters.")
            continue
        p2 = getpass.getpass("Confirm passphrase: ")
        if p1 != p2:
            print("  Passphrases didn't match — try again.")
            continue
        return p1


# ── Config mapping ────────────────────────────────────────────────────────────

def build_mobile_yaml(cfg, only: set[str] | None) -> str:
    """
    Convert the resolved CLI Config into the YAML format expected by AtcConfig
    on Android.  Only includes services the app currently supports.

    CLI key      → Android key
    proxmox      → proxmox           (same structure)
    pihole       → pihole_instances  (list, key rename)
    plex         → plex              (same)
    tautulli     → tautulli          (same)
    radarr       → radarr            (same)
    sonarr       → sonarr            (same)
    seerr        → seerr             (same)
    portainer    → portainer         (same)
    beszel       → beszel            (same)
    """
    want = only  # None = include everything supported

    mobile: dict = {}

    # Proxmox
    if _want("proxmox", want) and cfg.proxmox and cfg.proxmox.host:
        mobile["proxmox"] = {
            "host":        cfg.proxmox.host,
            "port":        cfg.proxmox.port,
            "user":        cfg.proxmox.user,
            "token_name":  cfg.proxmox.token_name,
            "token_value": cfg.proxmox.token_value,
            "verify_ssl":  cfg.proxmox.verify_ssl,
        }

    # Pi-hole  (CLI key = "pihole", Android key = "pihole_instances")
    if _want("pihole", want) and cfg.pihole_instances:
        mobile["pihole_instances"] = [
            {
                "name":     p.name,
                "host":     p.host,
                "port":     p.port,
                "password": p.password,
                "primary":  p.primary,
            }
            for p in cfg.pihole_instances
        ]

    # Plex
    if _want("plex", want) and cfg.plex:
        mobile["plex"] = {
            "host":  cfg.plex.host,
            "port":  cfg.plex.port,
            "token": cfg.plex.token,
        }

    # Tautulli
    if _want("tautulli", want) and cfg.tautulli:
        mobile["tautulli"] = {
            "host":    cfg.tautulli.host,
            "port":    cfg.tautulli.port,
            "api_key": cfg.tautulli.api_key,
        }

    # Radarr
    if _want("radarr", want) and cfg.radarr:
        mobile["radarr"] = {
            "host":      cfg.radarr.host,
            "port":      cfg.radarr.port,
            "https":     cfg.radarr.https,
            "api_key":   cfg.radarr.api_key,
            "base_path": cfg.radarr.base_path,
        }

    # Sonarr
    if _want("sonarr", want) and cfg.sonarr:
        mobile["sonarr"] = {
            "host":      cfg.sonarr.host,
            "port":      cfg.sonarr.port,
            "https":     cfg.sonarr.https,
            "api_key":   cfg.sonarr.api_key,
            "base_path": cfg.sonarr.base_path,
        }

    # Seerr (Overseerr / Jellyseerr)
    if _want("seerr", want) and cfg.seerr:
        mobile["seerr"] = {
            "host":    cfg.seerr.host,
            "port":    cfg.seerr.port,
            "https":   cfg.seerr.https,
            "api_key": cfg.seerr.api_key,
        }

    # Portainer
    if _want("portainer", want) and cfg.portainer:
        mobile["portainer"] = {
            "host":    cfg.portainer.host,
            "port":    cfg.portainer.port,
            "api_key": cfg.portainer.api_key,
        }

    # Beszel
    if _want("beszel", want) and cfg.beszel:
        mobile["beszel"] = {
            "host":    cfg.beszel.host,
            "port":    cfg.beszel.port,
            "api_key": cfg.beszel.api_key,
        }

    if not mobile:
        print("No matching services found in config.yaml for the requested filter.")
        sys.exit(1)

    return yaml.dump(mobile, default_flow_style=False, allow_unicode=True, sort_keys=False)


def _want(service: str, only: set[str] | None) -> bool:
    return only is None or service in only


# ── QR generation ─────────────────────────────────────────────────────────────

QR_CAPACITY_BYTES = 2953   # max for L error-correction, binary mode
# Encryption overhead per payload: 7 (prefix) + base64(16 salt + 12 nonce + 16 GCM
# tag) ≈ 7 + ceil(44/3)*4 = ~66 bytes before counting the YAML itself, plus
# base64 inflates the YAML's own bytes by ~4/3. Budget conservatively.
_ENCRYPTED_OVERHEAD_BYTES = 80


def make_qr(data: str) -> "qrcode.QRCode":
    qr = qrcode.QRCode(
        error_correction=qrcode.constants.ERROR_CORRECT_L,
        box_size=1,
        border=2,
    )
    qr.add_data(data.encode("utf-8"))
    qr.make(fit=True)
    return qr


# ── CLI ───────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--config", type=Path,
        help="Path to config.yaml (default: infrastructure/cli/config.yaml)",
    )
    parser.add_argument(
        "--only", metavar="SERVICE[,SERVICE]",
        help="Comma-separated services to include: proxmox,pihole,plex,tautulli,radarr,sonarr,seerr,portainer,beszel",
    )
    parser.add_argument(
        "--save", type=Path, metavar="FILE.png",
        help="Save QR as a PNG image (requires: uv add 'qrcode[pil]')",
    )
    parser.add_argument(
        "--print-yaml", action="store_true",
        help="Print the generated YAML to stdout",
    )
    args = parser.parse_args()

    only = {s.strip().lower() for s in args.only.split(",")} if args.only else None

    print("Resolving config (keychain secrets will be fetched automatically)…")
    cfg = load_config(args.config)

    yaml_content = build_mobile_yaml(cfg, only)
    plain_size = len(yaml_content.encode("utf-8"))

    # Rough pre-check before paying for a KDF derivation — base64 inflates by
    # ~4/3 plus the fixed overhead; the real check after encryption is authoritative.
    if plain_size + _ENCRYPTED_OVERHEAD_BYTES > QR_CAPACITY_BYTES * 3 // 4:
        print(f"\n✗  Config is {plain_size} bytes — too large once encrypted/encoded "
              f"for one QR (capacity {QR_CAPACITY_BYTES} bytes).")
        print("   Use --only to include only the services you need right now.")
        sys.exit(1)

    if args.print_yaml:
        print("\n── Generated YAML (plaintext — local debugging only, never encoded) ──")
        print(yaml_content)
        print("────────────────────────────────────────────────────────\n")

    passphrase = _prompt_passphrase()
    payload = encrypt_payload(yaml_content, passphrase)
    byte_size = len(payload.encode("utf-8"))

    if byte_size > QR_CAPACITY_BYTES:
        print(f"\n✗  Encrypted payload is {byte_size} bytes — exceeds QR capacity "
              f"({QR_CAPACITY_BYTES} bytes).")
        print("   Use --only to include only the services you need right now.")
        sys.exit(1)

    qr = make_qr(payload)

    service_names = _summarise(yaml_content)
    print(f"\n── ATC Mobile Config QR  (encrypted · {byte_size} bytes · {service_names}) ──\n")

    # invert=True looks correct on dark terminals (most dev setups)
    qr.print_ascii(invert=True)

    print("\n  Scan with ATC app → Settings → Scan QR Code → enter the same passphrase")
    print("  Tip: if the scan fails, zoom out in your terminal or use --save to get a PNG.\n")

    if args.save:
        _save_png(qr, args.save)


def _summarise(yaml_content: str) -> str:
    import re
    top_keys = re.findall(r"^(\w+):", yaml_content, re.MULTILINE)
    labels = {"proxmox": "Proxmox", "pihole_instances": "Pi-hole",
              "plex": "Plex", "tautulli": "Tautulli",
              "radarr": "Radarr", "sonarr": "Sonarr", "seerr": "Seerr",
              "portainer": "Portainer", "beszel": "Beszel"}
    return " · ".join(labels.get(k, k) for k in top_keys if k in labels)


def _save_png(qr: "qrcode.QRCode", path: Path) -> None:
    try:
        from PIL import Image  # noqa: F401
        img = qr.make_image(fill_color="black", back_color="white")
        img.save(path)
        print(f"  PNG saved to {path}")
    except ImportError:
        print("  Pillow not installed — cannot save PNG.")
        print("  Run: uv add 'qrcode[pil]'")


if __name__ == "__main__":
    main()
